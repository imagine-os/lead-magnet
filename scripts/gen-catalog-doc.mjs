// Generates docs/reference/catalog.md from src/engine/catalog/industries.ts (D-063). Run: npm run catalog:doc
// Read-only against the catalog: this script never edits industries.ts, it only renders what is there.
import { writeFileSync } from 'node:fs';
import { INDUSTRIES, INDUSTRY_KEYS, CATALOG_TOOLS } from '../src/engine/catalog/industries.ts';

const usd = (n) => `$${n.toLocaleString('en-US', { minimumFractionDigits: n % 1 ? 2 : 0, maximumFractionDigits: 2 })}`;
const scaleTag = (item) => (item.per_seat && item.per_location ? ' /seat /location' : item.per_seat ? ' /seat' : item.per_location ? ' /location' : '');
const esc = (s) => String(s).replace(/\|/g, '\\|');

let subIndustryCount = 0;
let toolRowCount = 0;

const lines = [];
lines.push('# Industry catalog reference');
lines.push('');
lines.push('Generated by `npm run catalog:doc` (`scripts/gen-catalog-doc.mjs`) from `src/engine/catalog/industries.ts` - **do not hand-edit this file**, it will be overwritten. Regenerate it after any catalog change so this stays a mirror of the code, not a second source of truth.');
lines.push('');
lines.push(`Generated: ${new Date().toISOString().slice(0, 10)} · ${INDUSTRY_KEYS.length} industries · ${CATALOG_TOOLS.length} distinct tools in the index. Prices are plausible 2026 list prices (USD/month), reviewed and dated per tool (D-063) - not vendor quotes; rows reviewed 2026-09-20 were added by the reference-systems pass (\`docs/reference/reference-systems.md\`) and their note starts with "Estimate". A sub-industry with **Depth** replaces the industry's departments, KPIs, pains, motifs, roles and meter for prospects that store it (\`industryFor(p)\`, T55).`);
lines.push('');
lines.push('## Contents');
lines.push('');
for (const key of INDUSTRY_KEYS) lines.push(`- [${INDUSTRIES[key].label.en} (\`${key}\`)](#${key.replace(/_/g, '-')})`);
lines.push('');

for (const key of INDUSTRY_KEYS) {
  const ind = INDUSTRIES[key];
  lines.push(`## ${ind.label.en} \`${key}\``);
  lines.push('');
  lines.push(`*${ind.label.es}*`);
  lines.push('');
  if (ind.sub?.length) {
    subIndustryCount += ind.sub.length;
    lines.push('**Sub-industries:**');
    lines.push('');
    lines.push('| Key | EN | ES | Extra tools (prevalence in this sub) | Roles | Depth |');
    lines.push('| --- | --- | --- | --- | --- | --- |');
    const depth = (sub) => { const parts = []; if (sub.departments?.length) parts.push(`${sub.departments.length} departments`); if (sub.kpis?.length) parts.push(`${sub.kpis.length} KPIs`); if (sub.pains?.length) parts.push(`${sub.pains.length} pains`); if (sub.meter) parts.push(`meter: ${esc(sub.meter.label.en)} ${sub.meter.value} / ${sub.meter.max}`); return parts.join(' · ') || '-'; };
    for (const sub of ind.sub) lines.push(`| \`${sub.key}\` | ${esc(sub.name.en)} | ${esc(sub.name.es)} | ${(sub.extra_tools ?? []).map((t) => `\`${t}\`${sub.extra_prevalence?.[t] != null ? ` ${Math.round(sub.extra_prevalence[t] * 100)}%` : ''}`).join(', ') || '-'} | ${(sub.roles ?? []).join(', ') || '-'} | ${depth(sub)} |`);
    lines.push('');
    for (const sub of ind.sub.filter((x) => x.departments?.length || x.kpis?.length)) {
      lines.push(`*\`${sub.key}\` depth* (what \`industryFor(p)\` shows a prospect with this sub-industry instead of the industry's own):`);
      lines.push('');
      if (sub.departments?.length) lines.push(`- Departments: ${sub.departments.map((d) => `${esc(d.en)} / ${esc(d.es)}`).join(' · ')}`);
      if (sub.kpis?.length) lines.push(`- KPIs: ${sub.kpis.map((k) => `${esc(k.label.en)} (${esc(k.label.es)}) **${esc(k.sample)}**`).join(' · ')}`);
      if (sub.pains?.length) lines.push(`- Pains: ${sub.pains.map((x) => esc(x.en)).join(' · ')}`);
      if (sub.meter) lines.push(`- Meter: ${esc(sub.meter.label.en)} / ${esc(sub.meter.label.es)} - ${sub.meter.value} of ${sub.meter.max}${sub.meter.unit ? ` ${esc(sub.meter.unit.en)}` : ''}`);
      lines.push('');
    }
  }
  if (ind.meter) { lines.push(`**Meter (industry-level):** ${esc(ind.meter.label.en)} / ${esc(ind.meter.label.es)} - ${ind.meter.value} of ${ind.meter.max}${ind.meter.unit ? ` ${esc(ind.meter.unit.en)}` : ''} (the owner / manager home shows it as a gauge).`); lines.push(''); }
  lines.push('| Tool | Category | List price | Replaces | Prevalence | Reviewed | Note |');
  lines.push('| --- | --- | --- | --- | --- | --- | --- |');
  for (const item of [...ind.stack].sort((a, b) => b.monthly_cost - a.monthly_cost)) {
    toolRowCount++;
    lines.push(`| ${esc(item.tool)} | ${esc(item.category)} | ${usd(item.monthly_cost)}${scaleTag(item)} | ${esc(item.replaced_by)} | ${Math.round(item.prevalence * 100)}% | ${item.price_reviewed ?? '-'} | ${item.price_source_note ? esc(item.price_source_note) : ''} |`);
  }
  lines.push('');
}

lines.push('---');
lines.push('');
lines.push(`Totals: ${INDUSTRY_KEYS.length} industries, ${subIndustryCount} sub-industries, ${toolRowCount} tool listings (${CATALOG_TOOLS.length} distinct tools) across the catalog.`);
lines.push('');

writeFileSync(new URL('../docs/reference/catalog.md', import.meta.url), lines.join('\n'));
console.log(`wrote docs/reference/catalog.md (${INDUSTRY_KEYS.length} industries, ${subIndustryCount} sub-industries, ${toolRowCount} tool listings)`);
